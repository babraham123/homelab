#!/bin/bash
# secsvcs backup: a logical Postgres dump plus the config and small state of every
# service, staged under /var/opt/backups for pve1's backup_orchestrator to pull.
# Usage:
#   src/nodes/secsvcs/backup.sh
# Not staged, on purpose: the postgres18 volume (the dump replaces it), vmdata and
# vldata (metrics and logs, large and rebuilt by collection), /var/opt/ntfy (cache).

# shellcheck source=src/base/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/../../base/lib.sh"

# shellcheck source=src/base/debian/backup_lib.sh
source "${rendered}/base/debian/backup_lib.sh"

stage_init

# Postgres: Authelia, LLDAP, Gatus, Grafana and Vaultwarden state. Connect via
# the container hostname, not the socket or loopback, so pg_hba's scram-sha-256 rule
# applies instead of the image's trust rules.
dir=$(dump_dir postgres)
dump="${dir}/pg_dumpall-$(date +%Y-%m-%dT%H%M%S).sql.zst"
PGPASSWORD="$("${rendered}/base/podman/get_secret.sh" postgres_password)"
export PGPASSWORD
if ! podman exec -e PGPASSWORD postgres \
    pg_dumpall -h pgdb.janedoe.com -U postgres | zstd -q -o "${dump}.tmp"; then
  rm -f "${dump}.tmp"
  die "pg_dumpall failed"
fi
mv "${dump}.tmp" "$dump"

# ntfy-idp-push's passkeys: losing them means re-enrolling every phone. Its backup command
# copies the SQLite database consistently while it serves.
dir=$(dump_dir ntfy_idp_push)
dump="${dir}/ntfy_idp_push-$(date +%Y-%m-%dT%H%M%S).sqlite"
if ! podman exec ntfy_idp_push ntfy-idp-push backup - > "${dump}.tmp"; then
  rm -f "${dump}.tmp"
  die "ntfy-idp-push backup failed"
fi
mv "${dump}.tmp" "$dump"

# Config trees, including Traefik's acme.json, the LLDAP data dir and this host's
# secrets key and bundle. Certificates are regenerated by pve1 but cost nothing here.
stage_paths /etc/opt /etc/ssh /etc/systemd/system /etc/containers/systemd
# SQLite under a running process (Grafana, ntfy): a plain copy is usually consistent
# and both are easy to rebuild, so no stop/dump hook for them.
stage_volume grafanadata
stage_volume ntfydb
# Vaultwarden's attachments, sends, config.json and rsa_key*, which existing sessions need
stage_volume vaultwardendata

stage_send
